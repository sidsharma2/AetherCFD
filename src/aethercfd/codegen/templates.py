def render(t: CodeTemplate, name: str, base: str = "") -> dict[str, str]:
    out = {}
    for path, content in t.files.items():
        out[path.replace("{NAME}", name)] = content.replace("{NAME}", name).replace("{BASE}", base)
    return out


def case_entries(t: CodeTemplate, name: str) -> list[tuple[str, str, str]]:
    return [(f, k.replace("{NAME}", name), v.replace("{NAME}", name)) for f, k, v in t.case_entries]


def template(tid: str) -> CodeTemplate | None:
    return next((t for t in TEMPLATES if t.id == tid), None)
