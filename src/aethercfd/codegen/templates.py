"""Templates for your own OpenFOAM physics: turbulence models, sources, boundary conditions, solvers.

Each template is a small, correct starting point for ONE fork (APIs differ between ESI and Foundation),
built against the installed OpenFOAM with wmake inside WSL (codegen.build), plus the case entries that
switch it on. The flagship is k-epsilon with Pope's round-jet correction (Pope 1978, AIAA J. 16(3)): an
extra epsilon source C_pope * chi * eps^2/k with the vortex-stretching invariant
chi = Omega_ij Omega_jk S_ki (k/eps)^3, C_pope = 0.79 -- the standard fix for the round-jet anomaly in
piloted jet flames (Sandia D/E/F).
"""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass
class CodeTemplate:
    id: str
    title: str
    family: str  # esi | foundation | any
    kind: str  # library | runtime | solver
    summary: str
    files: dict[str, str] = field(default_factory=dict)  # relative path -> content ({NAME} placeholders)
    case_entries: list[tuple[str, str, str]] = field(default_factory=list)  # (file, keyword path, value)
    usage: str = ""
    wmake: str = "libso"  # wmake target ("" for runtime-compiled templates)


_POPE_H = r"""/*---------------------------------------------------------------------------*\
    {NAME}: k-epsilon with Pope's round-jet correction (generated by AetherCFD)

    epsilon equation gains  + C_pope * alpha*rho * chi * epsilon^2/k,
    chi = Omega_ij Omega_jk S_ki (k/epsilon)^3   (Pope, AIAA J. 16(3), 1978),
    C_pope = 0.79 by default (keyword Cpope in {NAME}Coeffs).
    Robustness: S is the DEVIATORIC strain (removes spurious divergence from continuity errors, so
    chi = 0 in planar 2-D flow as it should be) and |chi| is clipped to chiMax (default 1; the correction
    is calibrated for developed round jets where |chi| ~ 0.1).
    Built on the installed kEpsilon through its epsilonSource() hook.
\*---------------------------------------------------------------------------*/

#ifndef {NAME}_H
#define {NAME}_H

#include "kEpsilon.H"

namespace Foam
{
namespace RASModels
{

template<class BasicTurbulenceModel>
class {NAME}
:
    public kEpsilon<BasicTurbulenceModel>
{
protected:

    dimensionedScalar Cpope_;
    dimensionedScalar chiMax_;

    virtual tmp<fvScalarMatrix> epsilonSource() const;


public:

    typedef typename BasicTurbulenceModel::alphaField alphaField;
    typedef typename BasicTurbulenceModel::rhoField rhoField;
    typedef typename BasicTurbulenceModel::transportModel transportModel;

    TypeName("{NAME}");

    {NAME}
    (
        const alphaField& alpha,
        const rhoField& rho,
        const volVectorField& U,
        const surfaceScalarField& alphaRhoPhi,
        const surfaceScalarField& phi,
        const transportModel& transport,
        const word& propertiesName = turbulenceModel::propertiesName,
        const word& type = typeName
    );

    virtual ~{NAME}() = default;

    virtual bool read();
};

} // End namespace RASModels
} // End namespace Foam

#ifdef NoRepository
    #include "{NAME}.C"
#endif

#endif
"""

_POPE_C = r"""#include "{NAME}.H"
#include "fvc.H"
#include "fvm.H"

namespace Foam
{
namespace RASModels
{

template<class BasicTurbulenceModel>
tmp<fvScalarMatrix> {NAME}<BasicTurbulenceModel>::epsilonSource() const
{
    const volScalarField& k = this->k_;
    const volScalarField& eps = this->epsilon_;
    const volTensorField gradU(fvc::grad(this->U_));
    const volSymmTensorField S(dev(symm(gradU)));
    const volTensorField W(skew(gradU));

    // vortex-stretching invariant (dimensionless), clipped
    const volScalarField kByEps(k/max(eps, this->epsilonMin_));
    const volScalarField chi
    (
        max(min(((W & W) && S)*pow3(kByEps), chiMax_), -chiMax_)
    );

    return
        kEpsilon<BasicTurbulenceModel>::epsilonSource()
      + fvm::Su
        (
            Cpope_*this->alpha_()*this->rho_()*chi()*sqr(eps())/max(k(), this->kMin_),
            this->epsilon_
        );
}


template<class BasicTurbulenceModel>
{NAME}<BasicTurbulenceModel>::{NAME}
(
    const alphaField& alpha,
    const rhoField& rho,
    const volVectorField& U,
    const surfaceScalarField& alphaRhoPhi,
    const surfaceScalarField& phi,
    const transportModel& transport,
    const word& propertiesName,
    const word& type
)
:
    kEpsilon<BasicTurbulenceModel>
    (
        alpha, rho, U, alphaRhoPhi, phi, transport, propertiesName, type
    ),
    Cpope_
    (
        dimensioned<scalar>::getOrAddToDict("Cpope", this->coeffDict_, 0.79)
    ),
    chiMax_
    (
        dimensioned<scalar>::getOrAddToDict("chiMax", this->coeffDict_, 1.0)
    )
{
    if (type == typeName)
    {
        this->printCoeffs(type);
    }
}


template<class BasicTurbulenceModel>
bool {NAME}<BasicTurbulenceModel>::read()
{
    if (kEpsilon<BasicTurbulenceModel>::read())
    {
        Cpope_.readIfPresent(this->coeffDict());
        chiMax_.readIfPresent(this->coeffDict());
        return true;
    }
    return false;
}

} // End namespace RASModels
} // End namespace Foam
"""

