"""Read-only model of an OpenFOAM case on disk. Loading a case never writes anything into it."""

from __future__ import annotations

import itertools
import re
from dataclasses import dataclass, field
from enum import StrEnum
from pathlib import Path

from aethercfd.case.fork_detect import ForkGuess, detect_fork
from aethercfd.core.paths import PathSafety, onedrive_hint, openfoam_path_safety, win_to_wsl
from aethercfd.core.textio import decode_bytes
from aethercfd.foamdict.cst import Atom, DictNode, ListNode
from aethercfd.foamdict.parser import parse
from aethercfd.foamdict.semantic import DictView

_TIME_NAME = re.compile(r"^[-+]?(\d+(\.\d*)?|\.\d+)([eE][-+]?\d+)?$")
_NOTE_CELLS = re.compile(r"nCells:\s*(\d+)")
_GENERATED = re.compile(r"(generated by|auto-?generated|do not (hand-)?edit)", re.IGNORECASE)


class FileKind(StrEnum):
    DICT = "dict"
    FIELD = "field"
    MESH = "mesh"
    LOG = "log"
    SCRIPT = "script"
    POST = "postProcessing"
    DOC = "doc"
    OTHER = "other"


@dataclass(frozen=True)
class Patch:
    name: str
    type: str
    n_faces: int | None = None
    in_groups: tuple[str, ...] = ()


@dataclass
class Region:
    name: str  # "" for single-region cases
    mesh_dir: Path
    patches: list[Patch] = field(default_factory=list)
    n_cells: int | None = None

    @property
    def is_2d(self) -> bool:
        return any(p.type == "empty" for p in self.patches)

    @property
    def is_axisymmetric(self) -> bool:
        return any(p.type == "wedge" for p in self.patches)


@dataclass
class Case:
    root: Path
    wsl_path: str
    path_safety: PathSafety
    regions: list[Region]
    times: list[tuple[float, str]]  # (value, dir name), sorted
    application: str | None
    solver_module: str | None  # Foundation foamRun 'solver'
    fork_guess: ForkGuess
    n_processors: int = 0
    collated: bool = False
    generated_by: str | None = None
    on_onedrive: bool = False
    processor_times: list[tuple[float, str]] = field(default_factory=list)  # results of a decomposed run

    @property
    def name(self) -> str:
        return self.root.name

    @property
    def multi_region(self) -> bool:
        return len(self.regions) > 1 or (len(self.regions) == 1 and self.regions[0].name != "")

    @property
    def decomposed(self) -> bool:
        return self.n_processors > 0 or self.collated

    @property
    def latest_time(self) -> str | None:
        return self.times[-1][1] if self.times else None

    @property
    def latest_result_time(self) -> str | None:
        """Latest time with results, reconstructed or still in processor*/ (a decomposed run's results live
        there until reconstructPar)."""
        best = max(self.times[-1:] + self.processor_times[-1:], default=None)
        return best[1] if best else None

    @property
    def solver_label(self) -> str:
        if self.solver_module:
            return f"foamRun -solver {self.solver_module}"
        return self.application or "?"

    @property
    def n_cells(self) -> int | None:
        vals = [r.n_cells for r in self.regions if r.n_cells is not None]
        return sum(vals) if vals else None


def is_time_dir(name: str) -> bool:
    return bool(_TIME_NAME.match(name))


def _read_dict(path: Path) -> DictView | None:
    try:
        data = path.read_bytes()
    except OSError:
        return None
    text, _ = decode_bytes(data)
    return DictView(parse(text))


def read_patches(boundary_file: Path) -> list[Patch]:
    """Patches from polyMesh/boundary (a root-level ``N ( name { ... } ... )`` list)."""
    view = _read_dict(boundary_file)
    if view is None:
        return []
    out: list[Patch] = []
    for m in view.doc.root.entries():
        if m.value is None or not m.value.items or not isinstance(m.value.items[0], ListNode):
            continue
        items = m.value.items[0].items
        for a, b in itertools.pairwise(items):
            if isinstance(a, Atom) and isinstance(b, DictNode):
                fields: dict[str, str] = {}
                groups: tuple[str, ...] = ()
                for e in b.entries():
                    if e.value is None:
                        continue
                    if e.key.name == "inGroups":
                        lst = next((i for i in e.value.items if isinstance(i, ListNode)), None)
                        if lst:
                            groups = tuple(x.text for x in lst.items if isinstance(x, Atom))
                    else:
                        fields[e.key.name] = view.doc.text(e.value.start, e.value.end)
                nf = fields.get("nFaces")
                out.append(Patch(a.text, fields.get("type", "?"), int(nf) if nf and nf.isdigit() else None, groups))
    return out


def read_n_cells(owner_file: Path) -> int | None:
    try:
        with open(owner_file, "rb") as f:
            head = f.read(2048).decode("latin-1")
    except OSError:
        return None
    m = _NOTE_CELLS.search(head)
    return int(m.group(1)) if m else None


def _regions(root: Path) -> list[str]:
    rp = root / "constant" / "regionProperties"
    if not rp.exists():
        return [""]
    view = _read_dict(rp)
    if view is None:
        return [""]
    lk = view.lookup("regions")
    names: list[str] = []
    if lk and lk.entry is not None and lk.entry.value is not None:
        for it in lk.entry.value.items:
            if isinstance(it, ListNode):
                # regions ( fluid (a b) solid (c d) )
                for sub in it.items:
                    if isinstance(sub, ListNode):
                        names += [x.text for x in sub.items if isinstance(x, Atom)]
    return names or [""]


def load_case(root: str | Path) -> Case:
    root = Path(root)
    if not (root / "system" / "controlDict").exists():
        raise FileNotFoundError(f"{root} is not an OpenFOAM case (no system/controlDict)")
    wsl = win_to_wsl(str(root))
    regions: list[Region] = []
    for rname in _regions(root):
        mesh = root / "constant" / rname / "polyMesh" if rname else root / "constant" / "polyMesh"
        regions.append(Region(rname, mesh, read_patches(mesh / "boundary"), read_n_cells(mesh / "owner")))
    times: list[tuple[float, str]] = []
    nproc = 0
    collated = False
    for p in root.iterdir():
        if not p.is_dir():
            continue
        if is_time_dir(p.name):
            times.append((float(p.name), p.name))
        elif p.name.startswith("processor"):
            if p.name[9:].isdigit():
                nproc += 1
            elif p.name.startswith("processors"):
                collated = True
    times.sort()
    ptimes: list[tuple[float, str]] = []
    if nproc and (root / "processor0").is_dir():
        ptimes = sorted((float(q.name), q.name) for q in (root / "processor0").iterdir()
                        if q.is_dir() and is_time_dir(q.name))
    cd = _read_dict(root / "system" / "controlDict")
    app = cd.get_text("application") if cd else None
    solver = cd.get_text("solver") if cd else None
    head = cd.doc.source[:3000] if cd else ""
    gen = _GENERATED.search(head)
    generated_by = None
    if gen:
        line = head[head.rfind("\n", 0, gen.start()) + 1: head.find("\n", gen.start())]
        generated_by = line.strip("/ *").strip()
    return Case(root=root, wsl_path=wsl, path_safety=openfoam_path_safety(wsl), regions=regions, times=times,
                application=app.strip() if app else None, solver_module=solver.strip() if solver else None,
                fork_guess=detect_fork(root), n_processors=nproc, collated=collated, generated_by=generated_by,
                on_onedrive=onedrive_hint(str(root)), processor_times=ptimes)


def classify_file(case_root: Path, path: Path) -> FileKind:
    rel = path.relative_to(case_root).parts
    name = path.name
    if not rel:
        return FileKind.OTHER
    if rel[0] == "postProcessing":
        return FileKind.POST
    if "polyMesh" in rel:
        return FileKind.MESH
    if name.startswith("log.") or name.endswith(".log") or (rel[0] == "logs"):
        return FileKind.LOG
    if name in ("Allrun", "Allclean", "Allrun.pre", "Allrun.post") or path.suffix in (".sh", ".py"):
        return FileKind.SCRIPT
    if path.suffix in (".md", ".txt", ".pdf", ".png"):
        return FileKind.DOC
    if rel[0] in ("system", "constant"):
        return FileKind.DICT
    if is_time_dir(rel[0]) or rel[0] in ("0.orig",):
        return FileKind.FIELD
    return FileKind.OTHER
