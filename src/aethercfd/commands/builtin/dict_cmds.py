"""dict.set / dict.insert / dict.remove: structured, minimal edits to OpenFOAM dictionaries."""

from __future__ import annotations

import re
from pathlib import Path

from pydantic import BaseModel

from aethercfd.commands.base import (
    Actor,
    CheckResult,
    Command,
    CommandPlan,
    CommandSpec,
    FileChange,
    Risk,
    unified_diff,
)
from aethercfd.commands.executor import Context
from aethercfd.core.textio import read_snapshot
from aethercfd.foamdict.cst import FoamDocument
from aethercfd.foamdict.edits import (
    EditError,
    TextEdit,
    apply_edits,
    insert_entry,
    remove_entry,
    set_or_insert,
    set_value,
)
from aethercfd.foamdict.parser import parse

_GENERATED = re.compile(r"(generated by[^\n]*|do not (hand-)?edit)", re.IGNORECASE)


def _plan_edit(cmd: Command, ctx: Context, actor: Actor, params: BaseModel, file: str, summary: str,
               make_edits) -> CommandPlan:
    path = Path(file)
    plan = CommandPlan(cmd.spec.name, params.model_dump(), actor, cmd.spec.risk, summary)
    if not path.exists():
        plan.preconditions.append(CheckResult(False, f"{path} does not exist"))
        return plan
    snap = read_snapshot(path)
    doc: FoamDocument = parse(snap.text)
    if not doc.ok:
        d = next(x for x in doc.diagnostics if x.severity == "error")
        line, _ = doc.line_col(d.start)
        plan.preconditions.append(CheckResult(False, f"{path.name} has a syntax error at line {line} "
                                                     f"({d.message}); fix it in the raw editor first"))
        return plan
    try:
        edits: list[TextEdit] = make_edits(doc, snap.newline)
    except EditError as exc:
        plan.preconditions.append(CheckResult(False, str(exc)))
        return plan
    new_text = apply_edits(snap.text, edits)
    after = snap.encode(new_text)
    if after == snap.encode():
        plan.consequences.append("no change")
        return plan
    if (m := _GENERATED.search(snap.text[:3000])) is not None:
        plan.consequences.append(f"{path.name} says '{m.group(0).strip()[:80]}': regenerating it will overwrite "
                                 "this change")
    plan.file_changes.append(FileChange(path, snap.sha256, after, unified_diff(path, snap.text, new_text),
                                        snap.encode()))
    return plan


class SetParams(BaseModel):
    file: str
    key: str  # "PIMPLE/nOuterCorrectors"
    value: str  # raw OpenFOAM text, e.g. "3", "uniform (1 0 0)", "Gauss linear"
    insert_if_missing: bool = False
    allow_nonliteral: bool = False


class DictSet(Command):
    spec = CommandSpec("dict.set", SetParams, Risk.EDIT, "Set a dictionary keyword's value")

    def plan(self, ctx: Context, params: SetParams, actor: Actor) -> CommandPlan:  # type: ignore[override]
        def edits(doc, nl):
            if params.insert_if_missing:
                return set_or_insert(doc, params.key, params.value, newline=nl)
            return set_value(doc, params.key, params.value, allow_nonliteral=params.allow_nonliteral)

        return _plan_edit(self, ctx, actor, params, params.file,
                          f"{Path(params.file).name}: {params.key} = {params.value}", edits)


class InsertParams(BaseModel):
    file: str
    dict_path: str  # "" for the top level
    key: str
    value: str


class DictInsert(Command):
    spec = CommandSpec("dict.insert", InsertParams, Risk.EDIT, "Add a keyword to a dictionary")

    def plan(self, ctx: Context, params: InsertParams, actor: Actor) -> CommandPlan:  # type: ignore[override]
        where = f"{params.dict_path}/" if params.dict_path else ""
        return _plan_edit(self, ctx, actor, params, params.file,
                          f"{Path(params.file).name}: add {where}{params.key} {params.value}",
                          lambda doc, nl: insert_entry(doc, params.dict_path, params.key, params.value, newline=nl))


class RemoveParams(BaseModel):
    file: str
    key: str


class DictRemove(Command):
    spec = CommandSpec("dict.remove", RemoveParams, Risk.EDIT, "Remove a keyword from a dictionary")

    def plan(self, ctx: Context, params: RemoveParams, actor: Actor) -> CommandPlan:  # type: ignore[override]
        return _plan_edit(self, ctx, actor, params, params.file, f"{Path(params.file).name}: remove {params.key}",
                          lambda doc, nl: remove_entry(doc, params.key))


COMMANDS = [DictSet(), DictInsert(), DictRemove()]
